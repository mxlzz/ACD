"""Condense a Cycles comparative benchmark into a permanent human-auditable report.

This deliberately avoids 'winner' language if seeds, references or scene quality
do not pass their *diagnostic* controls. Results are descriptive, not perceptual.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path


def prepare(root: Path, *, experiment: str="E0020") -> str:
    meta=json.loads((root/"metadata.json").read_text())
    report=json.loads((root/"metrics.json").read_text())
    aggregate=json.loads((root/"seed_aggregate.json").read_text())
    focus=("Raw","STANDARD","HIGH","SUPER","NATIVE_COMP_OIDN")
    ref=report.get("reference_quality_diagnostic") or {}
    seed=aggregate.get("seed_diversity_audit") or {}
    lines=[
        f"# {experiment} — Cozy Kitchen Cycles denoising pilot (AUTOGENERATED; CHECK BEFORE CLAIMS)",
        "",
        f"- Input scene SHA256: `{meta.get('source_blend_sha256')}`; Blender `{meta.get('blender')}`; scene `{meta.get('scene_name')}`, frame `{meta.get('frame')}`.",
        f"- Resolution `{meta.get('resolution')}`, noisy samples `{meta.get('samples')}` x `{1+len(meta.get('extra_input_seeds', []))}` seeds `{[meta.get('seed'),*meta.get('extra_input_seeds', [])]}`; references `{meta.get('reference_samples')}` spp x `{2 if meta.get('second_reference') else 1}`.",
        "- **Evidence type:** real Cycles renders, same RenderLayer per method, finite-spp references. Not a perceptual study, convergence proof, or SID5 commercial benchmark.",
        f"- Seed diversity heuristic passed: **{aggregate.get('input_diversity_heuristic_passed')}**; references flagged large discrepancy: **{ref.get('large_reference_discrepancy_alert')}**; convergence proven: **{ref.get('convergence_proven')}**; sampling independence proven: **{aggregate.get('sampling_independence_proven')}**.",
        f"- Reference disagreement/raw error: `{ref.get('reference_disagreement_over_raw_error')}`; directly compared refs RMSE: `{(report.get('independent_reference_difference') or {}).get('rmse_linear')}`.",
        f"- Ranking RMSE mean (ONLY IF DIVERSITY HEURISTIC PASSED): `{aggregate.get('rank_by_mean_rmse')}`.",
        f"- Ranking edge-gradient mean: `{aggregate.get('rank_by_mean_edge_gradient_rmse')}`.",
        f"- First/second reference ranking agreement: `{report.get('reference_ranking_consistent')}`.",
        "",
        "| Method | RMSE linear mean | Edge gradient RMSE mean | Contrast ratio mean | MAE linear mean |",
        "|---|---:|---:|---:|---:|"
    ]
    def val(n): return "n/a" if n is None else f"{n:.7f}"
    for name in focus:
        if name not in aggregate["methods"]:continue
        a=aggregate["methods"][name]
        detail=aggregate.get("detail_methods",{}).get(name,{})
        def d(k):
            v=detail.get(k)
            return None if v is None else v.get("mean")
        lines.append(f"| {name} | {val(a['rmse_linear']['mean'])} | {val(d('edge_gradient_rmse'))} | {val(d('edge_contrast_ratio'))} | {val(a['mae_linear']['mean'])} |")
    lines.extend([
        "",
        "**Cautions:** Contrast ratio alone rewards oversharpening. RMSE can miss spatially important detail; edge gradients are asinh RGB and inherit noise in references. Low-resolution pilot cannot settle texture preservation. Independent seeds/converged reference cannot be established by image difference alone.",
        "",
        "**Next:** Inspect 1:1 crops / residuals; repeat with better references if their disagreement is material. Reserve a separate scene as withheld test before tuning.",
        ""
    ])
    return "\n".join(lines)


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--directory",required=True,type=Path)
    p.add_argument("--experiment", choices=("E0020","E0021"), default="E0020")
    p.add_argument("--output",required=True,type=Path)
    a=p.parse_args()
    text=prepare(a.directory,experiment=a.experiment)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(text,encoding="utf-8")
    print("E0020 SUMMARY")
    print(text)


if __name__=="__main__":main()
